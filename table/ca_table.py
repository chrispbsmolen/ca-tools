#!/usr/bin/env python3
"""ca_table - query the provenance-tracked covering array table.

The table (ca_table.csv, same directory) is append-only: one row per
evidence event. Tiers: CITED (traceable to a dated snapshot or paper),
VERIFIED (an explicit array is in hand and machine-checked, row carries
its SHA-256 and a verification stamp), FAILED_PENDING_RECHECK (a
verification attempt that failed its dimension check; each such row is
superseded by a later resolution row), SCREENED (an array screened on
column windows, not counted), DISPUTED (since 2026-10-23: an added row
beside a CITED row whose cited construction, as implemented and checked,
did not give a covering array at the recorded size; not counted, and the CITED row it
disputes is still counted), RETRACTED (since 2026-10-31: an added row beside a
VERIFIED or SCREENED row, same t, v, k, N and array_sha256, saying that row was
found wrong; not counted, and the row it retracts is no longer counted either).
Which rows count is defined once, in counted() below; the other tools import it.
Stair-step semantics: a row (t, v, k, N) means N runs
suffice for up to k columns.

derived.csv (same directory, regenerated by tools/derive_table.py on every
change) holds sizes that follow from the counted rows by published
constructions (fusing symbols, deriving a strength, Power CT and others),
each with its arithmetic. They are computed sizes, not arrays, and are never
part of counted(). best() gives the counted lookup; best_derived() also takes
derived.csv into account.

Usage:
  ca_table.py best T V K       best known N for strength T, V levels, K columns
  ca_table.py derived T V K    the same, also taking derived.csv into account
  ca_table.py verified T V     verified rows for (T, V), with stamps
  ca_table.py steps T V [KMAX] the full stair-step for (T, V)
  ca_table.py params           list available (t, v) combinations
"""
import csv, os, sys

DATA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ca_table.csv")
DERIVED = os.path.join(os.path.dirname(os.path.abspath(__file__)), "derived.csv")

def load():
    with open(DATA, newline="", encoding="utf-8") as f:
        return [r for r in csv.DictReader(f)]

COUNTED_TIERS = ("CITED", "VERIFIED")


def _key(r):
    return (str(r["t"]), str(r["v"]), str(r["k"]), str(r["N"]), r["array_sha256"])


METHODS = ("direct", "certificate", "certificate + fusing")


def check_method(r):
    """How a VERIFIED row was checked, from its stamp: "direct" (the array
    itself checked exhaustively), "certificate" (a covering perfect hash
    family checked exactly, expanded by the theorem of Sherwood, Martirosyan
    and Colbourn 2006), or "certificate + fusing" (that array with symbols
    fused, Lemma 3.1 of Colbourn, Keri, Rivas Soriano and Schlage-Puchta
    2010). None for rows of other tiers."""
    if r["tier"] != "VERIFIED":
        return None
    st = r.get("verify_stamp") or ""
    if st.startswith(("repcheck ", "repcheck_pp ", "cphfcheck ")):
        return "certificate + fusing" if "fused" in st else "certificate"
    return "direct"


def counted(rows, methods=None):
    """The rows that count as best known: tier CITED or VERIFIED, less every
    VERIFIED row that a RETRACTED row names (same t, v, k, N and array_sha256).
    With methods (a subset of METHODS), only VERIFIED rows checked by one of
    those methods count; for example methods=("direct",) counts only arrays
    checked directly. The default counts them all. This is the one
    definition; tools/consistency.py, tools/check_submission.py and
    tools/render_table.py import it, and ca_table.R mirrors it."""
    gone = {_key(r) for r in rows if r["tier"] == "RETRACTED"}
    return [r for r in rows if r["tier"] in COUNTED_TIERS
            and not (r["tier"] == "VERIFIED" and _key(r) in gone)
            and not (methods is not None and r["tier"] == "VERIFIED"
                     and check_method(r) not in methods)]


def evidence(rows):
    return counted(rows)

def best(rows, t, v, k, methods=None):
    cand = [int(float(r["N"])) for r in counted(rows, methods)
            if int(r["t"]) == t and int(r["v"]) == v and int(r["k"]) >= k]
    return min(cand) if cand else None

def load_derived():
    if not os.path.exists(DERIVED):
        return []
    with open(DERIVED, newline="", encoding="utf-8") as f:
        return [r for r in csv.DictReader(f)]

def best_derived(rows, derived, t, v, k, methods=None):
    """Like best(), also over derived.csv: (N, source) with source "counted" or the
    derived line's construction and arithmetic."""
    b = best(rows, t, v, k, methods)
    out = (b, "counted") if b is not None else (None, None)
    for d in derived:
        if int(d["t"]) == t and int(d["v"]) == v and int(d["k"]) >= k:
            n = int(d["N"])
            if out[0] is None or n < out[0]:
                out = (n, "derived: %s, %s" % (d["law"], d["arithmetic"]))
    return out

def main(argv):
    rows = load()
    if len(argv) >= 4 and argv[0] == "best":
        t, v, k = map(int, argv[1:4])
        n = best(rows, t, v, k)
        print(n if n is not None else "no entry")
    elif len(argv) >= 4 and argv[0] == "derived":
        t, v, k = map(int, argv[1:4])
        n, src = best_derived(rows, load_derived(), t, v, k)
        print(("%d (%s)" % (n, src)) if n is not None else "no entry")
    elif len(argv) >= 3 and argv[0] == "verified":
        t, v = int(argv[1]), int(argv[2])
        for r in rows:
            if r["tier"] == "VERIFIED" and int(r["t"]) == t and int(r["v"]) == v:
                print(r["k"], r["N"], r["array_sha256"][:12], r["verify_stamp"],
                      "|", r["notes"])
    elif len(argv) >= 3 and argv[0] == "steps":
        t, v = int(argv[1]), int(argv[2])
        kmax = int(argv[3]) if len(argv) > 3 else 10**9
        ev = sorted({(int(float(r["N"])), int(r["k"])) for r in evidence(rows)
                     if int(r["t"]) == t and int(r["v"]) == v and int(r["k"]) <= kmax})
        bestk = 0
        for n, k in ev:
            if k > bestk:
                print(n, k)
                bestk = k
    elif argv and argv[0] == "params":
        for t, v in sorted({(int(r["t"]), int(r["v"])) for r in rows}):
            print(t, v)
    else:
        print(__doc__)

if __name__ == "__main__":
    main(sys.argv[1:])
