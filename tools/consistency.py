#!/usr/bin/env python3
"""consistency.py - checks that the table, its arrays and its documents agree.

    python3 tools/consistency.py --check          every check (exit 1 on any problem)
    python3 tools/consistency.py --check --pr     the checks that make sense on a pull
                                                  request (the generated counts are
                                                  refreshed only after merge, so they
                                                  are not compared there)
    python3 tools/consistency.py --write          rewrite the generated counts block in
                                                  table/README.md from the data

Run from the repository root. Standard library only. The array files are
re-hashed by `tools/check_submission.py --selftest`, which the workflows run
beside this script; here the MANIFEST, the files and the table rows are
matched to each other, the table's structure is checked, the generated counts
are compared with the data, and every relative link and repository path named
in the Markdown documents is checked to exist.
"""
import collections
import csv
import os
import re
import subprocess
import sys

TABLE = "table/ca_table.csv"
MANIFEST = "table/MANIFEST.csv"
ARRAYS = "table/arrays"
CERTS = "table/certificates"
CERT_LIST = "table/certificates/CERTIFICATES.csv"
CERT_HEADER = ["file", "t", "v", "k", "N", "family", "sha256", "array_sha256", "check"]
README = "table/README.md"
HEADER = ["t", "v", "k", "N", "tier", "source_id", "source_detail", "snapshot_id",
          "array_sha256", "verify_stamp", "entered", "notes", "lb", "lb_evidence",
          "construction"]
MANIFEST_HEADER = ["file", "t", "v", "k", "N", "status", "sha256", "source_id",
                   "source_detail", "verify_stamp", "constant_rows"]
TIERS = {"CITED", "VERIFIED", "SCREENED", "FAILED_PENDING_RECHECK", "DISPUTED"}
SOURCES = {"S1", "S4", "S5", "S6", "S7", "S8"}
BASELINE_ROWS = 13641
BASELINE_SNAPSHOT = "colbourn-2024-11-ug"
BEGIN = "<!-- generated by tools/consistency.py from the data; do not edit by hand -->"
END = "<!-- end of generated block -->"
HEX64 = re.compile(r"^[0-9a-f]{64}$")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")

problems = []


def problem(msg):
    problems.append(msg)


def load():
    raw = open(TABLE, "rb").read()
    rows = list(csv.DictReader(open(TABLE, newline="", encoding="utf-8")))
    man = list(csv.DictReader(open(MANIFEST, newline="", encoding="utf-8")))
    return raw, rows, man


def num(x):
    return float(x)


# ---------------------------------------------------------------- counts

def stair_min(pts, k):
    """smallest N among (k', N) with k' >= k"""
    best = None
    for kk, n in pts:
        if kk >= k and (best is None or n < best):
            best = n
    return best


def counts(rows, man):
    tiers = collections.Counter(r["tier"] for r in rows)
    status = collections.Counter(m["status"] for m in man)
    msha = {m["sha256"] for m in man}
    cited = collections.defaultdict(list)
    full = collections.defaultdict(list)
    for r in rows:
        key = (r["t"], r["v"])
        if r["tier"] == "CITED" and r["source_id"] == "S1":
            cited[key].append((int(r["k"]), num(r["N"])))
        if r["tier"] in ("CITED", "VERIFIED"):
            full[key].append((int(r["k"]), num(r["N"])))
    nofile = [r for r in rows if r["tier"] == "VERIFIED" and r["array_sha256"] not in msha]
    nofile_src = collections.Counter(r["source_id"] for r in nofile)
    nofile_above = sum(1 for r in nofile
                       if num(r["N"]) > stair_min(full[(r["t"], r["v"])], int(r["k"])))
    # the frozen tables' eCAN and eCAK points are the baseline rows (CITED, S1);
    # compare the stair-step lookups over them alone with CITED (baseline and
    # literature) and VERIFIED rows together
    smaller_n = more_k = worse = 0
    for r in rows:
        if r["tier"] != "CITED" or r["source_id"] != "S1":
            continue
        key, k, n = (r["t"], r["v"]), int(r["k"]), num(r["N"])
        a, b = stair_min(cited[key], k), stair_min(full[key], k)
        if b < a:
            smaller_n += 1
        elif b > a:
            worse += 1
        ka = max(kk for kk, nn in cited[key] if nn <= n)
        kb = max(kk for kk, nn in full[key] if nn <= n)
        if kb > ka:
            more_k += 1
        elif kb < ka:
            worse += 1
    latest = max(r["entered"] for r in rows if DATE.match(r["entered"]))
    return dict(rows=len(rows), tiers=tiers, arrays=len(man), status=status,
                nofile=len(nofile), nofile_src=nofile_src, nofile_above=nofile_above,
                points=sum(1 for r in rows if r["source_id"] == "S1"), smaller_n=smaller_n, more_k=more_k, worse=worse,
                latest=latest)


def fmt(n):
    return "{:,}".format(n)


def block(c):
    t = c["tiers"]
    tier_txt = ", ".join("%s %s" % (k, fmt(t[k])) for k in
                         ("CITED", "VERIFIED", "SCREENED", "FAILED_PENDING_RECHECK", "DISPUTED") if t[k])
    src = ", ".join("%s %s" % (k, fmt(v)) for k, v in sorted(c["nofile_src"].items()))
    lines = [
        BEGIN,
        "Counts as of %s, the latest entry date in the table:" % c["latest"],
        "",
        "- rows: %s (%s)" % (fmt(c["rows"]), tier_txt),
        "- arrays on file: %s (%s equal the best-known size for their parameters at "
        "entry, %s are smaller than the November 2024 snapshot's recorded best%s)"
        % (fmt(c["arrays"]), fmt(c["status"]["equals_best"]), fmt(c["status"]["exceeds_snapshot"]),
           "".join(", %s %s %s" % (fmt(c["status"][st]), "is" if c["status"][st] == 1 else "are", what)
                   for st, what in (("above_snapshot", "larger than a snapshot value that has a DISPUTED row"),
                                    ("above_best", "larger than the best known size at entry, entered "
                                                   "through the submission check"),
                                    ("screened", "screened, not verified in full"))
                   if c["status"][st])),
        "- VERIFIED rows without a stored array: %s (%s), %s of them above the best "
        "known size" % (fmt(c["nofile"]), src, fmt(c["nofile_above"])),
        "- against the frozen tables at their %s points, the lookups over CITED and "
        "VERIFIED rows give a smaller N at %s and more columns at %s, and a worse "
        "value at %s" % (fmt(c["points"]), fmt(c["smaller_n"]), fmt(c["more_k"]), fmt(c["worse"])),
        END,
    ]
    return "\n".join(lines)


def current_block(text):
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < 0 or j < i:
        return None, i, j
    return text[i:j + len(END)], i, j + len(END)


# ---------------------------------------------------------------- checks

def check_structure(raw, rows, man):
    first = raw.split(b"\n", 1)[0].rstrip(b"\r").decode("utf-8")
    if first.split(",") != HEADER:
        problem("%s: header is %s, expected %s" % (TABLE, first, ",".join(HEADER)))
    nl, crlf = raw.count(b"\n"), raw.count(b"\r\n")
    if nl != crlf:
        problem("%s: mixed line endings (%d lines, %d with CRLF); the file is CRLF throughout"
                % (TABLE, nl, crlf))
    if not raw.endswith(b"\r\n"):
        problem("%s: does not end with CRLF" % TABLE)
    mraw = open(MANIFEST, "rb").read()
    if b"\r" in mraw:
        problem("%s: contains CR characters; the file is LF throughout" % MANIFEST)
    if list(man[0].keys()) != MANIFEST_HEADER if man else True:
        problem("%s: header differs from %s" % (MANIFEST, ",".join(MANIFEST_HEADER)))
    seen = collections.Counter()
    for i, r in enumerate(rows, start=2):
        where = "%s line %d" % (TABLE, i)
        if r["tier"] not in TIERS:
            problem("%s: unknown tier %r" % (where, r["tier"]))
        if r["source_id"] not in SOURCES:
            problem("%s: unknown source_id %r" % (where, r["source_id"]))
        for f in ("t", "v", "k"):
            if not r[f].isdigit():
                problem("%s: %s is not a positive integer: %r" % (where, f, r[f]))
        if not re.fullmatch(r"\d+", r["N"] or ""):
            problem("%s: N is not an integer: %r" % (where, r["N"]))
        if not DATE.match(r["entered"]):
            problem("%s: entered is not a date: %r" % (where, r["entered"]))
        if r["tier"] in ("VERIFIED", "SCREENED", "FAILED_PENDING_RECHECK"):
            if not HEX64.match(r["array_sha256"]):
                problem("%s: %s row without a sha256" % (where, r["tier"]))
            if not r["verify_stamp"]:
                problem("%s: %s row without a verify_stamp" % (where, r["tier"]))
        if r["tier"] in ("VERIFIED", "SCREENED") and not r["construction"]:
            problem("%s: %s row without a construction" % (where, r["tier"]))
        if r["lb"] or r["lb_evidence"]:
            problem("%s: lb and lb_evidence are reserved and empty in this version" % where)
        seen[tuple(r.values())] += 1
    for row, n in seen.items():
        if n > 1:
            problem("%s: a row appears %d times: %s" % (TABLE, n, ",".join(row)[:120]))
    s1 = [r for r in rows if r["source_id"] == "S1"]
    if len(s1) != BASELINE_ROWS or any(r["tier"] != "CITED" or r["snapshot_id"] != BASELINE_SNAPSHOT for r in s1):
        problem("%s: the baseline must be %d S1 rows, tier CITED, snapshot %s (found %d S1 rows)"
                % (TABLE, BASELINE_ROWS, BASELINE_SNAPSHOT, len(s1)))
    # a CITED row outside the baseline cites the literature (S7, since 2026-10-25): a DOI
    # or arXiv id as snapshot_id, no array fields, and notes that credit the paper
    for r in rows:
        if r["tier"] == "CITED" and r["source_id"] != "S1":
            key = ",".join((r["t"], r["v"], r["k"], r["N"]))
            if r["source_id"] != "S7" or not re.match(r"(doi:10\.|arXiv:)", r["snapshot_id"]):
                problem("%s: CITED row %s outside the baseline must be S7 with a DOI or arXiv id as snapshot_id"
                        % (TABLE, key))
            if r["array_sha256"] or r["verify_stamp"]:
                problem("%s: CITED row %s has array fields" % (TABLE, key))
            if "credit: " not in r["notes"] or not r["construction"].strip() or not r["source_detail"].strip():
                problem("%s: CITED row %s needs a credit in its notes, a source_detail and a construction"
                        % (TABLE, key))


def check_disputed(rows, man):
    """A DISPUTED row (defined 2026-10-23) disputes one CITED row: it carries the
    same t, v, k, N, at most one DISPUTED row per CITED row, it is not part of the
    baseline (source_id other than S1), and it has notes saying what failed, the
    recipe that was checked (source_detail) and a construction. An above_snapshot
    array is kept only beside a disputed entry: at its t, v, k the stair-step
    value over the baseline rows (CITED, S1) is a disputed row, and the array is larger."""
    cited = {(r["t"], r["v"], r["k"], r["N"]) for r in rows if r["tier"] == "CITED"}
    disputed = [r for r in rows if r["tier"] == "DISPUTED"]
    dkeys = collections.Counter((r["t"], r["v"], r["k"], r["N"]) for r in disputed)
    for key, n in dkeys.items():
        if n > 1:
            problem("%s: %d DISPUTED rows for the CITED row %s; one is enough"
                    % (TABLE, n, ",".join(key)))
    for r in disputed:
        key = (r["t"], r["v"], r["k"], r["N"])
        if key not in cited:
            problem("%s: DISPUTED row %s matches no CITED row" % (TABLE, ",".join(key)))
        if r["source_id"] == "S1":
            problem("%s: DISPUTED row %s has source S1; the baseline rows are CITED only"
                    % (TABLE, ",".join(key)))
        for f in ("notes", "source_detail", "construction"):
            if not r[f].strip():
                problem("%s: DISPUTED row %s without %s" % (TABLE, ",".join(key), f))
    cited_tv = collections.defaultdict(list)
    for r in rows:
        if r["tier"] == "CITED" and r["source_id"] == "S1":
            cited_tv[(r["t"], r["v"])].append(r)
    for m in man:
        if m["status"] != "above_snapshot":
            continue
        cand = [r for r in cited_tv[(m["t"], m["v"])] if int(r["k"]) >= int(m["k"])]
        best = min((int(r["N"]) for r in cand), default=None)
        ok = (best is not None and int(m["N"]) > best and
              any(int(r["N"]) == best and (r["t"], r["v"], r["k"], r["N"]) in dkeys for r in cand))
        if not ok:
            problem("%s: %s is above_snapshot, but the snapshot's stair-step value at its t, v, k is "
                    "not a disputed row smaller than it" % (MANIFEST, m["file"]))


def check_certificates(rows):
    """A certificate (since 2026-10-28) stands for an array too large to store: a
    covering perfect hash family, listed in CERTIFICATES.csv with its own SHA-256 and the
    SHA-256 of the array it expands to, checked exactly by tools/cphf/repcheck.c. Every
    file of the folder is listed, every listed file is there with that hash, and each
    certificate belongs to a VERIFIED row with the same t, v, k, N and array_sha256."""
    import hashlib
    if not os.path.isdir(CERTS):
        return
    if not os.path.exists(CERT_LIST):
        problem("%s/ has no CERTIFICATES.csv" % CERTS)
        return
    certs = list(csv.DictReader(open(CERT_LIST, newline="", encoding="utf-8")))
    if certs and list(certs[0].keys()) != CERT_HEADER:
        problem("%s: header differs from %s" % (CERT_LIST, ",".join(CERT_HEADER)))
        return
    files = set(os.listdir(CERTS)) - {"CERTIFICATES.csv"}
    listed = collections.Counter(c["file"] for c in certs)
    for f in sorted(files - set(listed)):
        problem("%s/%s is not listed in %s" % (CERTS, f, CERT_LIST))
    for c in certs:
        if listed[c["file"]] > 1:
            problem("%s: %s listed more than once" % (CERT_LIST, c["file"]))
        path = os.path.join(CERTS, c["file"])
        if not os.path.exists(path):
            problem("%s: %s is listed but not in %s/" % (CERT_LIST, c["file"], CERTS))
            continue
        if hashlib.sha256(open(path, "rb").read()).hexdigest() != c["sha256"]:
            problem("%s: %s does not have the listed sha256" % (CERT_LIST, c["file"]))
        match = [r for r in rows if r["tier"] == "VERIFIED" and r["array_sha256"] == c["array_sha256"]
                 and (r["t"], r["v"], r["k"], r["N"]) == (c["t"], c["v"], c["k"], c["N"])]
        if not match:
            problem("%s: %s has no VERIFIED row with the same t, v, k, N and array_sha256"
                    % (CERT_LIST, c["file"]))
        elif (match[0]["verify_stamp"].startswith("repcheck ")
              and not c["check"].startswith(match[0]["verify_stamp"].split(" (")[0])):
            problem("%s: %s: the check %r does not start with the row's stamp %r"
                    % (CERT_LIST, c["file"], c["check"][:40], match[0]["verify_stamp"]))
    # the other way: a row checked through a certificate has its certificate listed
    csha = {(c["t"], c["v"], c["k"], c["N"], c["array_sha256"]) for c in certs}
    for r in rows:
        if r["tier"] == "VERIFIED" and r["verify_stamp"].startswith("repcheck "):
            if (r["t"], r["v"], r["k"], r["N"], r["array_sha256"]) not in csha:
                problem("%s: VERIFIED row %s,%s,%s,%s is stamped by repcheck but has no certificate in %s"
                        % (TABLE, r["t"], r["v"], r["k"], r["N"], CERT_LIST))


def check_arrays(rows, man):
    files = set(os.listdir(ARRAYS)) if os.path.isdir(ARRAYS) else set()
    mfiles = collections.Counter(m["file"] for m in man)
    for f, n in mfiles.items():
        if n > 1:
            problem("%s: file %s listed %d times" % (MANIFEST, f, n))
        if f not in files:
            problem("%s: %s is listed but not in %s/" % (MANIFEST, f, ARRAYS))
    for f in sorted(files - set(mfiles)):
        problem("%s/%s is not listed in %s" % (ARRAYS, f, MANIFEST))
    bysha = collections.defaultdict(list)
    for r in rows:
        if r["array_sha256"]:
            bysha[r["array_sha256"]].append(r)
    for m in man:
        match = [r for r in bysha.get(m["sha256"], [])
                 if r["tier"] in ("VERIFIED", "SCREENED")
                 and (r["t"], r["v"], r["k"], r["N"]) == (m["t"], m["v"], m["k"], m["N"])]
        if not match:
            problem("%s: %s (sha256 %s) has no VERIFIED or SCREENED table row with the same "
                    "t, v, k, N" % (MANIFEST, m["file"], m["sha256"][:12]))
        if m["status"] not in ("equals_best", "exceeds_snapshot", "above_snapshot", "above_best", "screened"):
            problem("%s: %s has unknown status %r" % (MANIFEST, m["file"], m["status"]))


LINK = re.compile(r"\]\(([^)\s]+)\)")
CODE = re.compile(r"`([^`\s]+)`")
PATHLIKE = re.compile(r"^(\.\./|\./)?([A-Za-z0-9_.-]+/)+[A-Za-z0-9_.*-]+(\.[A-Za-z0-9]+)?/?$")
TOPDIRS = ("table/", "tools/", "submissions/", "results/", "r/", "docs/", ".github/", "../")


def tracked_markdown():
    try:
        out = subprocess.run(["git", "ls-files", "*.md"], capture_output=True, text=True, check=True).stdout
        return [p for p in out.split("\n") if p]
    except Exception:
        found = []
        for d, _, fs in os.walk("."):
            if "/.git" in d:
                continue
            found += [os.path.join(d, f)[2:] for f in fs if f.endswith(".md")]
        return found


def resolves(doc, ref):
    ref = ref.split("#", 1)[0].rstrip("/")
    if not ref:
        return True
    # relative to the document's folder or to any folder above it, up to the root
    base = os.path.dirname(doc)
    while True:
        cand = os.path.normpath(os.path.join(base, ref))
        if any(ch in cand for ch in "*<>") or os.path.exists(cand):
            return True
        if not base:
            return False
        base = os.path.dirname(base)


PLAIN = re.compile(r"(?<![\w/.`-])((?:\.\./)?(?:table|tools|submissions|results|r|docs)/[A-Za-z0-9_./-]*[A-Za-z0-9_-]\.(?:md|csv|py|R|c|txt|yml|rda|html))(?![\w/])")


def check_links():
    for doc in tracked_markdown():
        text = open(doc, encoding="utf-8").read()
        for m in LINK.finditer(text):
            ref = m.group(1)
            if re.match(r"^[a-z]+:", ref) or ref.startswith("#"):
                continue
            if not resolves(doc, ref):
                problem("%s: link to %s, which does not exist" % (doc, ref))
        for m in CODE.finditer(text):
            ref = m.group(1)
            if not PATHLIKE.match(ref) or not ref.startswith(TOPDIRS):
                continue
            if "<" in ref or "*" in ref:
                continue
            if not resolves(doc, ref):
                problem("%s: names `%s`, which does not exist" % (doc, ref))
        for m in PLAIN.finditer(text):
            ref = m.group(1)
            if not resolves(doc, ref):
                problem("%s: names %s, which does not exist" % (doc, ref))


def main():
    args = sys.argv[1:]
    raw, rows, man = load()
    c = counts(rows, man)
    text = open(README, encoding="utf-8").read()
    blk, i, j = current_block(text)
    if "--write" in args:
        if blk is None:
            sys.exit("%s has no generated block (%s ... %s)" % (README, BEGIN, END))
        new = text[:i] + block(c) + text[j:]
        if new != text:
            open(README, "w", encoding="utf-8").write(new)
            print("%s: generated counts updated" % README)
        else:
            print("%s: generated counts already current" % README)
        return 0
    if "--check" not in args:
        print(__doc__)
        return 2
    check_structure(raw, rows, man)
    check_arrays(rows, man)
    check_certificates(rows)
    check_disputed(rows, man)
    check_links()
    if c["worse"]:
        problem("the CITED and VERIFIED lookups are worse than the frozen tables at %d points" % c["worse"])
    if "--pr" not in args:
        if blk is None:
            problem("%s: generated counts block missing" % README)
        elif blk != block(c):
            problem("%s: generated counts are out of date; run python3 tools/consistency.py --write"
                    % README)
    for p in problems:
        print("PROBLEM  " + p)
    print("consistency: %d rows, %d arrays, %d problems" % (c["rows"], c["arrays"], len(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
