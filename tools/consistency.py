def stair_min(pts, k):
    """smallest N among (k', N) with k' >= k"""
    best = None
    for kk, n in pts:
        if kk >= k and (best is None or n < best):
            best = n
    return best


def counts(rows, man):
    tiers = collections.Counter(r["tier"] for r in rows)
    status = collections.Counter(m["status"] for m in man)
    msha = {m["sha256"] for m in man}
    cited = collections.defaultdict(list)
    full = collections.defaultdict(list)
    for r in rows:
        key = (r["t"], r["v"])
        if r["tier"] == "CITED" and r["source_id"] == "S1":
            cited[key].append((int(r["k"]), num(r["N"])))
    for r in counted(rows):
        full[(r["t"], r["v"])].append((int(r["k"]), num(r["N"])))
    nofile = [r for r in rows if r["tier"] == "VERIFIED" and r["array_sha256"] not in msha]
    nofile_src = collections.Counter(r["source_id"] for r in nofile)
    nofile_above = sum(1 for r in nofile
                       if num(r["N"]) > stair_min(full[(r["t"], r["v"])], int(r["k"])))
    # the frozen tables' eCAN and eCAK points are the baseline rows (CITED, S1);
    # compare the stair-step lookups over them alone with CITED (baseline and
    # literature) and VERIFIED rows together
    smaller_n = more_k = worse = 0
    for r in rows:
        if r["tier"] != "CITED" or r["source_id"] != "S1":
            continue
        key, k, n = (r["t"], r["v"]), int(r["k"]), num(r["N"])
        a, b = stair_min(cited[key], k), stair_min(full[key], k)
        if b < a:
            smaller_n += 1
        elif b > a:
            worse += 1
        ka = max(kk for kk, nn in cited[key] if nn <= n)
        kb = max(kk for kk, nn in full[key] if nn <= n)
        if kb > ka:
            more_k += 1
        elif kb < ka:
            worse += 1
    latest = max(r["entered"] for r in rows if DATE.match(r["entered"]))
    methods = collections.Counter(check_method(r) for r in rows if r["tier"] == "VERIFIED")
    return dict(methods=methods, rows=len(rows), tiers=tiers, arrays=len(man), status=status,
                nofile=len(nofile), nofile_src=nofile_src, nofile_above=nofile_above,
                points=sum(1 for r in rows if r["source_id"] == "S1"), smaller_n=smaller_n, more_k=more_k, worse=worse,
                latest=latest)


def fmt(n):
    return "{:,}".format(n)


def block(c):
    t = c["tiers"]
    tier_txt = ", ".join("%s %s" % (k, fmt(t[k])) for k in
                         ("CITED", "VERIFIED", "SCREENED", "FAILED_PENDING_RECHECK", "DISPUTED",
                          "RETRACTED") if t[k])
    src = ", ".join("%s %s" % (k, fmt(v)) for k, v in sorted(c["nofile_src"].items()))
    lines = [
        BEGIN,
        "Counts as of %s, the latest entry date in the table:" % c["latest"],
        "",
        "- rows: %s (%s)" % (fmt(c["rows"]), tier_txt),
        "- arrays on file: %s (%s equal the best-known size for their parameters at "
        "entry, %s are smaller than the November 2024 snapshot's recorded best%s)"
        % (fmt(c["arrays"]), fmt(c["status"]["equals_best"]), fmt(c["status"]["exceeds_snapshot"]),
           "".join(", %s %s %s" % (fmt(c["status"][st]), "is" if c["status"][st] == 1 else "are", what)
                   for st, what in (("above_snapshot", "larger than a snapshot value that has a DISPUTED row"),
                                    ("above_best", "larger than the best known size at entry, entered "
                                                   "through the submission check"),
                                    ("screened", "screened, not verified in full"))
                   if c["status"][st])),
        "- VERIFIED rows by how they were checked: %s" % ", ".join(
            "%s %s" % (m, fmt(c["methods"][m])) for m in METHODS if c["methods"][m]),
        "- VERIFIED rows without a stored array: %s (%s), %s of them above the best "
        "known size" % (fmt(c["nofile"]), src, fmt(c["nofile_above"])),
        "- against the frozen tables at their %s points, the lookups over CITED and "
        "VERIFIED rows give a smaller N at %s and more columns at %s, and a worse "
        "value at %s" % (fmt(c["points"]), fmt(c["smaller_n"]), fmt(c["more_k"]), fmt(c["worse"])),
        END,
    ]
    return "\n".join(lines)


def current_block(text):
    i, j = text.find(BEGIN), text.find(END)
    if i < 0 or j < 0 or j < i:
        return None, i, j
    return text[i:j + len(END)], i, j + len(END)


